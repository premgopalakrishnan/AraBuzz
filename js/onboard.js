  function finish() {
    if (location.search) history.replaceState({}, '', location.pathname);
    sessionStorage.removeItem('arabuzz.joining');
    close();
    if (w.UI && UI.afterOnboard) UI.afterOnboard(Cloud.whoAmI());
  }

