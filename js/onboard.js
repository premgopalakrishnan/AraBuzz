  let host = null;

  function mount() {
    host = document.getElementById('onboard');
    if (!host) {
      host = document.createElement('div');
      host.id = 'onboard';
      host.className = 'onboard';
      document.body.appendChild(host);
    }
    document.body.classList.add('onboarding');
    return host;
  }

  function close() {
    if (host) host.remove();
    host = null;
    document.body.classList.remove('onboarding');
  }

  function panel(inner, opts) {
    const o = opts || {};
    mount().innerHTML = `
      <div class="ob-wrap ${o.wide ? 'wide' : ''}">
        <div class="ob-brand">
          <img src="assets/icon-192.png" alt="">
          <div>
            <div class="ob-name"><span>Ara</span><span class="gold">Buzz</span></div>
            <div class="ob-tag">${esc(o.tag || 'Spelling practice')}</div>
          </div>
        </div>
        <div class="ob-card">${inner}</div>
        ${o.foot ? `<p class="ob-foot">${o.foot}</p>` : ''}
      </div>`;
    return host;
  }

  const busy = (btn, on, label) => {
    if (!btn) return;
    btn.disabled = on;
    btn.innerHTML = on ? '<span class="loader"></span> ' + (label || 'One moment') : btn.dataset.label;
  };

  function oops(msg) {
    const box = $('#obErr');
    if (box) { box.textContent = msg; box.style.display = 'block'; }
  }

  /* ==========================================================================
     1 · The invitation
     ========================================================================== */
