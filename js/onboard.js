/* ==========================================================================
   AraBuzz — onboard.js
   Getting a grown-up from an invitation to a child who can play.

   The order matters and is deliberate:

     invitation → sign in → your name → what this is (and agree) → a PIN → a child

   The consent screen sits fourth, not first. Nobody should be asked to agree to
   something before they have seen what it is. By the time it appears they have
   read the note, followed the link and typed their name — they know what they
   are agreeing to.

   Every step is one decision on one screen. A parent doing this on a phone,
   standing up, with a child asking for something, should never see two things
   at once.
   ========================================================================== */
